## Arithmetic Operators

a = 20
b = 5
print(a+b)
print(a-b)
print(a*b)
print(a/b)    # it gives the answer in float 

# Floor Division (it gives the answer in the interger)
print(a//b)

# Exponent 
print(a**b)
print(100**0.5)

# Modulus (remainder)
print(a%b)

