# basically follow the BORDMAS rule

## Comparison Operators (=, !=, <, >, <=, >=) (alwasy return boolean value True or False)

c = 10
d = 20
print(c == d)  # False
print(c != d)  # True
print(c < d)   # True
print(c > d)   # False
print(c <= d)  # True
print(c >= d)  # False

## Logical Operators (and, or, not) (alwasy return boolean value True or False)
e = True
f = False
print(e and f)  # False
print(e or f)   # True
print(not e)    # False